/**
 * Get the translation function for the given language.
 * Returns a function `t(key)` that looks up the translated string.
 */
export function getTranslator(lang: string): (key: string) => string {
  const langKey: LangKey = lang === "Hindi" ? "Hindi" : "English";
  const dict = translations[langKey];
  return (key: string) => dict[key] ?? translations.English[key] ?? key;
}

